// Generates src/data/groups.js with placeholder images (picsum.photos).
// Temporary helper — swap to scripts/fetch-data.mjs once real photos are wanted.
//
//   pnpm placeholder:data
import { writeFile, mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const __dirname = dirname(fileURLToPath(import.meta.url))

const GROUP_NAME = '(G)I-DLE'
const GROUP_ID = 'gidle'
const SIZES = [
  { w: 600, h: 850, orientation: 'portrait' }, // portrait
  { w: 900, h: 600, orientation: 'landscape' }, // landscape
  { w: 640, h: 640, orientation: 'square' }, // square
]

const MEMBERS = [
  { id: 'miyeon', name: 'Miyeon' },
  { id: 'minnie', name: 'Minnie' },
  { id: 'soyeon', name: 'Soyeon' },
  { id: 'yuqi', name: 'Yuqi' },
  { id: 'shuhua', name: 'Shuhua' },
]

// One avatar per member, in MEMBERS order.
const PROFILES = [
  'https://pbs.twimg.com/media/HLuHKTrbwAAQnX9?format=jpg&name=large',
  'https://pbs.twimg.com/media/HL6Miqia8AAjznY?format=jpg&name=large',
  'https://pbs.twimg.com/media/HL6MmojaIAIIDER?format=jpg&name=large',
  'https://pbs.twimg.com/media/HL6MrOJaoAA2esp?format=jpg&name=large',
  'https://pbs.twimg.com/media/HL6MvOHasAAEQB2?format=jpg&name=large',
]

let seq = 0

function item(member, n) {
  const size = SIZES[seq % SIZES.length]
  const id = `${member.id}-${String(n).padStart(2, '0')}`
  return {
    title: `${member.name.replace(/\s+/g, ' ')} — placeholder ${n}`,
    url: `https://picsum.photos/seed/idle-${id}/${size.w}/${size.h}`,
    w: size.w,
    h: size.h,
    member: member.name,
    id,
    groupId: GROUP_ID,
    groupName: GROUP_NAME,
    orientation: size.orientation,
  }
}

const groups = MEMBERS.map((m, i) => {
  const items = []
  seq = i * 10 // stagger orientations across members
  for (let n = 1; n <= 10; n++) items.push(item(m, n))
  return {
    id: m.id,
    name: m.name,
    kr: '',
    agency: 'CUBE Entertainment',
    debut: '2018.05.02',
    fandom: 'NEVERLAND',
    members: MEMBERS.map((x) => x.name),
    items,
  }
})

const total = groups.reduce((n, g) => n + g.items.length, 0)

const header =
  `// AUTO-GENERATED by scripts/gen-placeholder-data.mjs — ${new Date().toISOString()}\n` +
  `// ${groups.length} members · ${total} placeholder images (picsum.photos)\n`

const out =
  `${header}export const group = {\n` +
  `  id: '${GROUP_ID}',\n` +
  `  name: '${GROUP_NAME}',\n` +
  `  kr: '(여자)아이들',\n` +
  `  agency: 'CUBE Entertainment',\n` +
  `  debut: '2018.05.02',\n` +
  `  fandom: 'NEVERLAND',\n` +
  `  members: ${JSON.stringify(MEMBERS.map((m) => m.name))},\n` +
  `  profiles: ${JSON.stringify(PROFILES, null, 2).replace(/\n/g, '\n  ')},\n` +
  `};\n\n` +
  `export const groups = ${JSON.stringify(groups, null, 2)};\n\n` +
  `export const items = groups.flatMap((g) => g.items);\n\n` +
  `export default { group, groups, items };\n`

const file = resolve(__dirname, '../src/data/groups.js')
await mkdir(dirname(file), { recursive: true })
await writeFile(file, out, 'utf8')
console.log(`Wrote ${file} — ${groups.length} members, ${total} placeholder images.`)
